#!/usr/bin/env node
// The sounds from CLASSROOM A (not in the repo: put them in brayan/assets/audio/ first), as
// data URLs in brayan/js/sounds.js, so the page can decode them itself (for their pitch, their
// volume, and the visualizer at the door), even opened straight from the disk:
//   node brayan/tools/make_sounds.js
//   moan_2.mp3 -> what's in there, half awake;  moan_3.mp3 -> awake
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const out = {};
for (const [key, file] of [['moan2', 'moan_2.mp3'], ['moan3', 'moan_3.mp3']]) {
  const f = path.join(ROOT, 'assets/audio', file);
  out[key] = fs.existsSync(f) ? 'data:audio/mpeg;base64,' + fs.readFileSync(f).toString('base64') : '';
}
fs.writeFileSync(path.join(ROOT, 'js/sounds.js'), '// Generated by brayan/tools/make_sounds.js\nwindow.BRAYAN_SOUNDS = ' + JSON.stringify(out) + ';\n');
console.log('wrote brayan/js/sounds.js', Object.entries(out).map(([k, v]) => `${k} ${Math.round(v.length / 1024)} KB`).join(', '));
